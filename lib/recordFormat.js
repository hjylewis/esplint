const yaml = require("js-yaml");

const JSON_EXTENSION = ".json";
const YAML_EXTENSION = ".yml";

const FORMATS = {
  json: {
    name: "json",
    extension: JSON_EXTENSION,
    serialize: (record) => `${JSON.stringify(record, null, 2)}\n`,
    parse: (contents) => JSON.parse(contents),
  },
  yaml: {
    name: "yaml",
    extension: YAML_EXTENSION,
    serialize: serializeYaml,
    // Reading uses a real parser: the file may have been hand-edited, and
    // conflict resolution feeds us reconstructed documents.
    parse: (contents) => yaml.load(contents),
  },
};

const DEFAULT_FORMAT = FORMATS.json;

function getFormat(name) {
  return FORMATS[name] || DEFAULT_FORMAT;
}

function getFormatForPath(filePath) {
  return filePath.endsWith(YAML_EXTENSION) ? FORMATS.yaml : FORMATS.json;
}

function isValidFormatName(name) {
  return Object.prototype.hasOwnProperty.call(FORMATS, name);
}

// Emitted by hand rather than with a YAML library so the exact layout is
// guaranteed: block style, two-space indent, one rule per line, sorted keys.
// That's what keeps a single count change to a single changed line, which is the
// whole reason for offering YAML.
function serializeYaml(record) {
  const lines = [
    "# Generated by esplint. Check this file in.",
    `recordVersion: ${record.recordVersion}`,
    `configHash: ${quoteKeyOrValue(record.configHash)}`,
  ];

  if (record.trackedRules) {
    lines.push("trackedRules:");
    record.trackedRules.forEach((rule) => {
      lines.push(`  - ${quoteKeyOrValue(rule)}`);
    });
  }

  const files = record.files || {};
  const filePaths = Object.keys(files);

  if (!filePaths.length) {
    lines.push("files: {}");
  } else {
    lines.push("files:");
    filePaths.forEach((filePath) => {
      lines.push(`  ${quoteKeyOrValue(filePath)}:`);
      const ruleCounts = files[filePath];
      const rules = Object.keys(ruleCounts);
      if (!rules.length) {
        // An empty mapping has to stay inline; a bare key would parse as null.
        lines[lines.length - 1] = `  ${quoteKeyOrValue(filePath)}: {}`;
        return;
      }
      rules.forEach((rule) => {
        lines.push(`    ${quoteKeyOrValue(rule)}: ${ruleCounts[rule]}`);
      });
    });
  }

  return `${lines.join("\n")}\n`;
}

// Plain YAML scalars can't start with an indicator character, contain ": " or
// " #", or look like a number/bool/null. Rule ids like "@typescript-eslint/x"
// start with "@" and paths can contain ":", so quoting has to be deliberate --
// an unquoted key here would silently corrupt the record.
const NEEDS_QUOTES = /^[-?:,[\]{}#&*!|>'"%@`]|: |:$| #|^\s|\s$|^$/;
// Anything YAML would resolve to a non-string: decimals, hex, octal, binary,
// exponents, infinity/nan, booleans (including yes/no/on/off) and null. Missing
// one means the key silently changes type on read -- e.g. "0x1f" became 31.
const LOOKS_LIKE_NUMBER =
  /^([-+]?(\d[\d_]*(\.[\d_]*)?|\.[\d_]+)([eE][-+]?\d+)?|[-+]?0[xX][\da-fA-F_]+|[-+]?0[oO]?[0-7_]+|[-+]?0[bB][01_]+|[-+]?\.(inf|Inf|INF)|\.(nan|NaN|NAN))$/;
// Booleans and null are case-insensitive in YAML 1.1 ("TRUE", "True", "Null").
const LOOKS_LIKE_BOOL_OR_NULL = /^(true|false|yes|no|on|off|null|~)$/i;

function quoteKeyOrValue(value) {
  const string = String(value);

  if (
    NEEDS_QUOTES.test(string) ||
    LOOKS_LIKE_NUMBER.test(string) ||
    LOOKS_LIKE_BOOL_OR_NULL.test(string)
  ) {
    return `"${string.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
  }

  return string;
}

module.exports = {
  getFormat,
  getFormatForPath,
  isValidFormatName,
  DEFAULT_FORMAT,
  JSON_EXTENSION,
  YAML_EXTENSION,
};
